    h3(doc, "2.5.2 网络不确定性的工程化处理")
    para(doc, (
        "网络化控制真正困难的地方不是“连得上”，而是“连不上时仍然安全”。经典 NCS 研究指出，时延与"
        "丢包会改变闭环系统的极点分布，严重时使原本稳定的控制器失稳[[13,14]]。本设计因此不把控制律"
        "放进网络，而是从五个方面把不确定性挡在实时环之外。"
    ))
    para(doc, (
        "（1）时钟隔离与写入安全。控制节拍由片内 50 MHz 计数器产生，与网络时钟无关；网络侧只能写"
        "“目标角度、模式”等少数寄存器，由 FPGA 在节拍边界统一采样，不存在异步写入撕裂采样值的可能。"
        "换言之，网络延迟再大，也只是“目标晚一点到”，不会让控制周期变长或变短。"
    ))
    para(doc, (
        "（2）三级指令整形。任何来源的指令（按键、网页、云端）都要依次通过：协议层 ±180° 截断与"
        "20 ms 帧超时重同步；轨迹层梯形斜坡限制（27°/s、1000 counts/s²）；执行层 ±60 码倾角指令限幅。"
        "三级串联的结果是，即使上位机发来一个“瞬间转 180°”的误操作，机构看到的也只是一条受限的"
        "加减速曲线，摆杆不会因为目标突跳而失稳。"
    ))
    para(doc, (
        "（3）超时保持与看门狗。链路中断时，FPGA 保持当前目标继续平衡，不进入任何“等待网络”的状态；"
        "网关检测到掉线后每 10 s 重连一次，且重连过程不阻塞刷屏与收帧；若网关整体复位，现场环路仍按"
        "最后一次有效目标运行，直到操作者重新下达指令。对工业遥操作而言，“失联即停”并不总是安全——"
        "对倒立摆这类本身不稳定的对象，“失联即保持”才是更合理的选择。"
    ))
    para(doc, (
        "（4）链路质量的可观测性。遥测帧带序号与毫秒时标，接收端可以据此统计丢帧率、单向时延与抖动，"
        "而不是凭“感觉卡不卡”判断链路；CRC-16 与帧尾校验保证进入控制器的数据没有一位错误。可观测是"
        "可管理的前提，这一点在远程运维时尤其重要。"
    ))
    para(doc, (
        "（5）延迟补偿（设计）。在掌握单向时延后，有两种低成本补偿：一是把下行命令由“绝对目标”改为"
        "“相对增量”，使控制效果对时延不敏感；二是按“剩余距离 + 时延 × 当前速度”对目标做超前修正，"
        "相当于在目标层做一次 Smith 预估。两者都不改动内环结构，属于可开关的增强项。"
    ))
