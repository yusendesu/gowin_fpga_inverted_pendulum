def clear_body(doc):
    body = doc.element.body
    for child in list(body):
        if child.tag == qn("w:sectPr"):
            continue
        body.remove(child)


def _set_run_font(run, size=None, bold=None, superscript=False):
    if size is not None:
        run.font.size = Pt(size)
    if bold is not None:
        run.font.bold = bold
    if superscript:
        run.font.superscript = True
    # 中英文分别指定，避免混排时回退到 Calibri
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    rfonts.set(qn("w:ascii"), "Times New Roman")
    rfonts.set(qn("w:hAnsi"), "Times New Roman")
    rfonts.set(qn("w:eastAsia"), "宋体")


CITE_RE = re.compile(r"\[\[(\d+(?:,\s*\d+)*)\]\]")


def para(doc, text, style="Normal", align=None, size=None, bold=False,
         before=None, after=None, indent_chars=None, line=None, keep_next=False):
    p = doc.add_paragraph(style=style)
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    if before is not None:
        pf.space_before = Pt(before)
    if after is not None:
        pf.space_after = Pt(after)
    if line is not None:
        pf.line_spacing = line
    if indent_chars:
        pf.first_line_indent = Pt(indent_chars * (size or 12))

    pos = 0
    for m in CITE_RE.finditer(text):
        head = text[pos:m.start()]
        if head:
            _set_run_font(p.add_run(head), size, bold)
        _set_run_font(p.add_run("[%s]" % m.group(1)), size, bold, superscript=True)
        pos = m.end()
    tail = text[pos:]
    if tail:
        _set_run_font(p.add_run(tail), size, bold)
    if keep_next:
        pf.keep_with_next = True
    return p


